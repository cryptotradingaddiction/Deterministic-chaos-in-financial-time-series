#!/usr/bin/env python3
"""Hypothesis testing for dynamical invariants.

Script structure
----------------

This file is intentionally organized as a single executable pipeline because it
is called from several Windows batch scripts with different metric scopes. Read
it in the following order:

1. Global configuration and metric registry
   Defines the active embedding dimensions, bootstrap parameters, RQA defaults,
   and the set of metric names accepted by the CLI. This is where methodological
   constants shared with the batch scripts are centralized.

2. Surrogate and reference series generation
   Builds the three non-original comparison series:
   a full reshuffle, Gaussian white noise, and Student-t noise. Stationary
   bootstrap pseudo-series are generated by surrogate_sampling.py and consumed
   later in main().

3. Hypothesis-test helpers
   Implements the active stationary-bootstrap TS decision rule. Historical
   F-test/variance-testing code has been removed from this script.

4. TISEAN wrappers and output parsers
   Resolves and runs d2.exe, c2t.exe, and lyap_k.exe, then parses their text
   output blocks. This section converts command-line tool outputs into numeric
   NumPy arrays used by the invariant extractors.

5. Dimension extractors: TAKENS and ELLNER
   Selects stable scaling/plateau windows. TAKENS is the plateau mean of the
   c2t-produced d_2^(T)(r') curve. ELLNER reuses that plateau interval
   [r_min, r_max] and integrates the .c2 correlation integral over it.

6. Lyapunov and RQA helpers
   Extracts a scalar Kantz largest-Lyapunov estimate from S(t), computes
   percentile-based RQA radii, enforces an effective Theiler window for PyRQA,
   and adds the custom TREND metric.

7. compute_invariants()
   The central dispatcher for one in-memory series. It writes the series to a
   temporary .dat file, runs only the external tools required by the requested
   metrics, and returns estimate/SD/count dictionaries.

8. main()
   The full CLI workflow: load original data, build reference series, compute
   original/reference/bootstrap invariants, calculate TS decisions, and write a
   parser-friendly summary file consumed by print_results.py and documents.py.

Correlation dimension is estimated via Takens' maximum-likelihood estimator
(eq. 8.75-8.76) and its Ellner extension (eq. 8.78):

    1. d2.exe writes the correlation integral C^(m)(r) into a .c2 file (and
       h2 / d2 by-products used elsewhere).
    2. c2t.exe converts .c2 into the Takens-Theiler curve d_2^(T)(r').
    3. A stable plateau in d_2^(T)(r') vs ln r' is detected automatically; the
       plateau end-points yield r_min and r_max.
    4. The Ellner extension d_2^(E) is computed directly from .c2 over
       [r_min, r_max] using equation 8.78.

Both values are kept as separate invariants:
    TAKENS = plateau mean of d_2^(T)(r') from c2t.exe,
    ELLNER = Ellner extension d_2^(E) from .c2 over the same plateau interval.

Current core test for TAKENS/ELLNER/LLE:
    1. Generate B stationary-bootstrap pseudo-series from the original series.
    2. Compute the invariant for each pseudo-series.
    3. Let boot_mean be the arithmetic mean and boot_sd the sample SD of those
       B invariant values.
    4. Compute the same invariant for one fully reshuffled series.
    5. TS = (boot_mean - invariant_reshuffle) / boot_sd.
       Reject H0 for |TS| > 3. This rejects the interpretation that the series
       is only independent random noise; it is evidence of structure/memory as a
       prerequisite for chaos, not a proof of chaos.

Normal and Student-t references are still computed as descriptive benchmarks.
RQA remains a scalar original-series summary without this bootstrap test.
"""
