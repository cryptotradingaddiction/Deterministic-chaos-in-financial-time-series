# ---------------------------------------------------------------------------
# Surrogate and reference series generation
# ---------------------------------------------------------------------------
#
# The current test uses exactly one fully reshuffled series as the independent
# noise reference. Gaussian and Student-t series are computed only as descriptive
# benchmarks with the same first two moments as the original log-return series.
# The stationary bootstrap samples are produced in surrogate_sampling.py because
# they are reused as a standalone sampling primitive.

def generate_single_surrogate(data: np.ndarray) -> np.ndarray:
    """Random permutation of the original series (randperm, no blocking).

    This destroys temporal ordering while preserving the empirical marginal
    distribution exactly. It is the "reshuffle" value in the TS denominator.
    """
    return np.random.permutation(data)


def generate_normal_series(mu: float, sigma: float, n: int) -> np.ndarray:
    """Gaussian white-noise reference with the original mean and SD."""
    return np.random.normal(mu, sigma, n)


def generate_t_series(mu: float, sigma: float, n: int, dof: float = T_DOF) -> np.ndarray:
    """t(dof) series scaled to (mu, sigma).

    t(dof) has zero mean and variance dof/(dof-2) for dof>2, so
    scale raw draws by sigma / sqrt(dof/(dof-2)) and shift by mu.
    """
    t_raw = np.random.standard_t(dof, n)
    t_sd = np.sqrt(dof / (dof - 2.0))
    return mu + sigma * (t_raw / t_sd)


# ---------------------------------------------------------------------------
# Hypothesis test helpers
# ---------------------------------------------------------------------------
#
# The current thesis output should be interpreted through
# TS=(boot_mean-reshuffle)/boot_sd with a fixed absolute threshold.

def invariant_bootstrap_ts_test(
    boot_mean: float,
    boot_sd: float,
    resh_value: float,
    threshold: float = DEFAULT_TS_THRESHOLD,
) -> tuple[float, float, str]:
    """TS=(boot_mean-reshuffle)/boot_sd with decision |TS| > threshold.

    The bootstrap distribution represents structured pseudo-series from the
    original data. The reshuffled value represents independent random ordering.
    A large absolute TS means the invariant under structured resampling is far
    from the invariant under full temporal destruction.
    """
    if not (np.isfinite(boot_mean) and np.isfinite(boot_sd) and np.isfinite(resh_value)):
        return np.nan, np.nan, "insufficient data"
    if boot_sd <= 0.0:
        return np.nan, np.nan, "no sd"
    ts = float((boot_mean - resh_value) / boot_sd)
    abs_ts = abs(ts)
    decision = "reject H0" if abs_ts > threshold else "fail to reject H0"
    return ts, abs_ts, decision


