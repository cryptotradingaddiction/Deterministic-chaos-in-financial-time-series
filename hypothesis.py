def resolve_tool(tool_name):
    """Resolve a TISEAN executable without hard-coding one installation path.

    Resolution order:
      1. TISEAN_BIN environment variable,
      2. repository-local Tisean_3.0.0/bin directory,
      3. PATH lookup, with and without the Windows .exe suffix.

    Keeping this flexible is important because the code is used both from
    Windows batch scripts and from direct Python smoke tests.
    """
    from_env = os.environ.get("TISEAN_BIN")
    if from_env:
        candidate = os.path.join(from_env, f"{tool_name}.exe")
        if os.path.exists(candidate):
            return candidate
    local_bin = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "Tisean_3.0.0", "bin", f"{tool_name}.exe",
    )
    if os.path.exists(local_bin):
        return local_bin
    which = shutil.which(tool_name)
    if which:
        return which
    which_exe = shutil.which(f"{tool_name}.exe")
    if which_exe:
        return which_exe
    raise FileNotFoundError(f"TISEAN executable for '{tool_name}' was not found.")


def run_d2(data_file, delay, theiler, output_prefix, eps_min=None, eps_max=None):
    """Run TISEAN d2.exe. Optional `eps_min`/`eps_max` set `-r` / `-R` scale bounds.

    The default `eps_min` / `eps_max` strategy in this pipeline (see
    `compute_invariants`) is 0.25*sigma .. 0.5*sigma of the analysed series,
    matching the book's practical recommendation for the Takens scale range.
    """
    # `d2.exe` is the common source for the current dimension path:
    # .c2 -> Takens and Ellner dimension estimates,
    # .h2 -> generated by TISEAN but no longer consumed by hypothesis.py,
    # .d2 -> local-slope diagnostic plots only.
    cmd = [resolve_tool("d2"), f"-d{delay}", f"-M1,{M_D2}", f"-t{theiler}",
           f"-#{D2_EPSILON_STEPS}", f"-N{D2_PAIR_LIMIT}"]
    if eps_min is not None and np.isfinite(eps_min) and eps_min > 0.0:
        cmd.append(f"-r{eps_min}")
    if eps_max is not None and np.isfinite(eps_max) and eps_max > 0.0:
        cmd.append(f"-R{eps_max}")
    cmd += ["-o", output_prefix, data_file]
    subprocess.run(cmd, check=True, capture_output=True, text=True)
    return output_prefix + ".d2", output_prefix + ".h2", output_prefix + ".c2"


def run_c2t(c2_file, output_file):
    """Run TISEAN c2t using relative paths to avoid FORTRAN path-length limits."""
    # The Windows TISEAN build uses old FORTRAN fixed-length path buffers.
    # Running from the output directory and passing basenames avoids silent
    # truncation for long thesis result paths.
    #
    # Methodological role:
    # c2t converts the correlation integral C^(m)(r) from .c2 into Takens'
    # maximum-likelihood correlation-dimension curve d_2^(T)(r'), i.e. the
    # practical form of the book's equations (8.75)-(8.76). This script does not
    # implement the all-pairs Takens average directly; it delegates that part to
    # TISEAN and then selects a stable plateau from the resulting curve.
    cwd = os.path.dirname(os.path.abspath(c2_file))
    cmd = [
        resolve_tool("c2t"),
        "-V0",
        "-o",
        os.path.basename(output_file),
        os.path.basename(c2_file),
    ]
    subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True)
    return output_file


def run_lyap_k(data_file, delay, output_file):
    # Kantz / largest-Lyapunov setup:
    #
    # The book motivates the largest Lyapunov exponent through the exponential
    # separation of nearby trajectories (equation 8.94). In reconstructed phase
    # space, lyap_k estimates the averaged logarithmic divergence S(t) from
    # neighbourhoods U_k around randomly selected reference states W (equation
    # 8.95). The exponent is then the slope of the linear part of S(t) vs t.
    #
    # Options used here:
    #   -m3 -M3 : compute only embedding dimension m=3, matching the rest of the
    #             thesis invariant workflow.
    #   -n500   : use about 500 reference states W, consistent with the book's
    #             practical recommendation that |W| around 500 is usually enough.
    #   -s10    : require approximately 10 neighbours in each U_k, matching the
    #             book's recommendation that each reference point should have
    #             several neighbours while keeping neighbourhoods local.
    #
    # We intentionally do not pass a Theiler window to lyap_k here. The Theiler
    # value used for d2/RQA is not automatically equivalent to the exclusion
    # choices for Kantz's method, and keeping this explicit avoids hidden coupling.
    cmd = [resolve_tool("lyap_k"), f"-d{delay}", f"-m{M_LYAP}", f"-M{M_LYAP}",
           "-n", "500", "-s", "10", "-o", output_file, data_file]
    subprocess.run(cmd, check=True, capture_output=True, text=True)


def extract_tagged_block(path, dim=M_D2, tag="#dim"):
    """Read a two-column block identified by '#dim=' or '#m=' from TISEAN outputs.

    TISEAN outputs usually contain several blocks:
      * .c2/.d2/.h2 label embedding blocks as "#dim=<m>",
      * c2t labels Takens blocks as "#m=<m>".

    The first column is always the scale r (or r'), and the second column is the
    metric value at that scale. Higher columns, if present, are ignored here.
    """
    rows = []
    current_dim = None
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as handle:
            for line in handle:
                stripped = line.strip()
                if not stripped:
                    continue
                if stripped.startswith(tag):
                    try:
                        current_dim = int(stripped.split("=")[1].strip())
                    except (ValueError, IndexError):
                        current_dim = None
                    continue
                if stripped.startswith("#") or stripped.startswith("!"):
                    continue
                if current_dim != dim:
                    continue
                parts = stripped.split()
                if len(parts) < 2:
                    continue
                try:
                    rows.append((float(parts[0]), float(parts[1])))
                except ValueError:
                    continue
    except Exception:
        return np.empty((0, 2), dtype=float)
    return np.array(rows, dtype=float)


def select_plateau_values(rows, min_points=MIN_PLATEAU_POINTS):
    """Select a stable scaling/plateau window from (epsilon, value) rows.

    Returns `(y_values, r_min, r_max)` where `y_values` are the plateau values
    sorted by ln(epsilon) and `r_min`, `r_max` are the epsilon end-points of the
    selected window (in the original linear scale). `r_min` / `r_max` are NaN if
    no usable rows were supplied.
    """
    arr = np.asarray(rows, dtype=float)
    if arr.size == 0 or arr.ndim != 2 or arr.shape[1] < 2:
        return np.array([], dtype=float), np.nan, np.nan

    eps = arr[:, 0]
    values = arr[:, 1]
    mask = np.isfinite(eps) & np.isfinite(values) & (eps > 0.0) & (values > 0.0)
    eps = eps[mask]
    values = values[mask]
    if values.size == 0:
        return np.array([], dtype=float), np.nan, np.nan

    # Sort by log scale because both local slopes and Takens estimates are
    # interpreted visually/methodologically as functions of ln(r).
    order = np.argsort(np.log(eps))
    eps_sorted = eps[order]
    x = np.log(eps_sorted)
    y = values[order]
    n = y.size
    if n < min_points:
        return y, float(eps_sorted[0]), float(eps_sorted[-1])

    # Window scoring favours flat, low-variance, and reasonably long regions.
    #
    # Book connection:
    # After equation (8.77), the text recommends treating d_2^(T)(r') as a
    # function of scale r' and estimating the correlation dimension from a
    # plateau in the graph d_2^(T)(r') versus ln(r'), instead of choosing a single
    # ad hoc r'. This function operationalizes that instruction. The score is
    # deliberately transparent: penalize slope and relative spread, add a small
    # bonus for longer intervals.
    best_score = -np.inf
    best_ij = (0, n)
    for i in range(0, n - min_points + 1):
        for j in range(i + min_points, n + 1):
            xs = x[i:j]
            ys = y[i:j]
            mean_abs = abs(float(np.mean(ys))) + 1e-12
            try:
                slope, _ = np.polyfit(xs, ys, 1)
            except Exception:
                continue
            rel_slope = abs(float(slope)) / mean_abs
            rel_sd = float(np.std(ys, ddof=1)) / mean_abs if ys.size > 1 else np.inf
            length_bonus = (j - i) / n
            score = 0.10 * length_bonus - rel_slope - rel_sd
            if score > best_score:
                best_score = score
                best_ij = (i, j)

    i, j = best_ij
    return y[i:j], float(eps_sorted[i]), float(eps_sorted[j - 1])


def _pearson_abs(x, y):
    """Absolute Pearson correlation with guards for degenerate windows."""
    if len(x) < 2 or len(y) < 2:
        return np.nan
    sx = float(np.std(x, ddof=1))
    sy = float(np.std(y, ddof=1))
    if sx <= 0.0 or sy <= 0.0:
        return np.nan
    return abs(float(np.corrcoef(x, y)[0, 1]))


def _mean_sd_n(values):
    """Return mean, sample SD, and finite-count for an estimator vector."""
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if values.size == 0:
        return np.nan, np.nan, 0
    mean = float(np.mean(values))
    sd = float(np.std(values, ddof=1)) if values.size > 1 else np.nan
    return mean, sd, int(values.size)


def extract_takens_plateau(takens_file, dim=M_D2):
    """Find a stable plateau on d_2^(T)(r') for embedding m=`dim`.

    Returns `(mean_val, sd_val, n_val, r_min, r_max)`:
      * `mean_val`/`sd_val`/`n_val` summarise the Takens values inside the plateau;
      * `r_min`/`r_max` are the radius end-points of that plateau (eq. 8.78 in the
        book). `r_min`/`r_max` are NaN if no plateau could be found.
    """
    # c2t produces d_2^(T)(r') as a curve:
    #
    #   d_2^(T)(r') = < log(r' / r_ij) >^(-1)                         (8.75)
    #
    # and, equivalently in terms of the correlation integral,
    #
    #   d_2^(T)(r') = C^(m)(r') / integral_0^{r'} C^(m)(r) / r dr       (8.76)
    #
    # The book explicitly notes that r' is a free scale parameter. Rather than
    # fixing a single r' by hand, it recommends computing the full curve and
    # choosing a plateau in d_2^(T)(r') versus ln(r'). That is exactly what
    # select_plateau_values() does below.
    #
    # The returned mean is the standalone TAKENS invariant. The returned r_min
    # and r_max are not arbitrary bounds: they are the selected plateau interval,
    # later reused by compute_ellner_from_c2() for equation (8.78).
    #
    # Note on uncertainty:
    # Equation (8.77) gives a theoretical standard deviation for a single Takens
    # estimate at a fixed r' in terms of the number of close pairs M_C(r'). Here
    # we report the empirical SD of the plateau values instead. That SD is used
    # as an orientation for plateau stability; the formal hypothesis-test SD is
    # computed across the B stationary-bootstrap invariant estimates.
    rows = extract_tagged_block(takens_file, dim=dim, tag="#m")
    if rows.size == 0:
        return np.nan, np.nan, 0, np.nan, np.nan
    y, r_min, r_max = select_plateau_values(rows)
    if y.size == 0:
        return np.nan, np.nan, 0, np.nan, np.nan
    mean_val, sd_val, n_val = _mean_sd_n(y)
    return mean_val, sd_val, n_val, r_min, r_max


def compute_ellner_from_c2(c2_file, r_min, r_max, dim=M_D2):
    """Ellner extension of Takens' estimator (book eq. 8.78).

    `d_2^(E) = [C^(m)(r_max) - C^(m)(r_min)] / integral_{r_min}^{r_max} C(r)/r dr`.
    `r_min`/`r_max` are typically taken from the Takens plateau auto-detected on
    the d_2^(T)(r') curve so that they bracket the linear scaling region.
    Returns NaN if the integral cannot be evaluated.
    """
    # Ellner's extension is introduced after the book explains a weakness of the
    # raw Takens estimator: d_2^(T)(r') averages over all distances below r'.
    # If the correlation integral contains several scaling regions, including
    # every distance from 0 to r' can blur the desired region. Ellner's formula
    # solves this by restricting the estimator to a finite scaling interval:
    #
    #   d_2^(E) =
    #       [ C^(m)(r_max) - C^(m)(r_min) ]
    #       / integral_{r_min}^{r_max} C^(m)(r) / r dr                 (8.78)
    #
    # In this implementation, r_min and r_max are not hand-selected. They come
    # from the plateau of d_2^(T)(r') detected in extract_takens_plateau(). Thus
    # TAKENS and ELLNER are tied to the same observed scaling region.
    #
    # Equation (8.79) gives a standard-deviation expression for Ellner's estimate
    # using M_C(r_max) and a theta-like ratio. We do not use that theoretical
    # formula as the hypothesis-test uncertainty; instead the test uses the
    # empirical SD across stationary-bootstrap ELLNER estimates, which is the
    # quantity requested by the current supervisor-aligned testing procedure.
    #
    # Numerically, we interpolate C(r_min) and C(r_max), because the detected
    # plateau endpoints need not coincide exactly with .c2 grid points.
    rows = extract_tagged_block(c2_file, dim=dim, tag="#dim")
    if rows.size == 0:
        return np.nan
    if not (np.isfinite(r_min) and np.isfinite(r_max)) or r_min <= 0.0 or r_max <= r_min:
        return np.nan
    r = rows[:, 0]
    c = rows[:, 1]
    # The integral C(r)/r and the logarithmic scale interpretation require
    # strictly positive radii and strictly positive correlation integrals.
    finite = np.isfinite(r) & np.isfinite(c) & (r > 0.0) & (c > 0.0)
    r = r[finite]
    c = c[finite]
    if r.size < 2:
        return np.nan
    order = np.argsort(r)
    r = r[order]
    c = c[order]
    # Restrict integration to the Takens-selected plateau interval. This is the
    # key Ellner idea: use only the finite scaling region, not all distances from
    # zero up to a single r'.
    mask = (r >= r_min) & (r <= r_max)
    if int(mask.sum()) < 2:
        return np.nan
    r_sel = r[mask]
    c_sel = c[mask]
    c_max = float(np.interp(r_max, r_sel, c_sel))
    c_min = float(np.interp(r_min, r_sel, c_sel))
    if not (np.isfinite(c_max) and np.isfinite(c_min)) or c_max <= c_min:
        return np.nan
    # Trapezoidal integration is adequate here because d2.exe already gives a
    # dense, ordered grid of radius values. NumPy renamed trapz -> trapezoid in
    # recent versions, so use the new function when available.
    integrand = c_sel / r_sel
    _trapz = getattr(np, "trapezoid", np.trapz)
    integral = float(_trapz(integrand, r_sel))
    if not np.isfinite(integral) or integral <= 0.0:
        return np.nan
    return float((c_max - c_min) / integral)


MIN_LYAP_LINEAR_POINTS = 5


def _best_linear_slope(x, y, min_points=MIN_LYAP_LINEAR_POINTS):
    """Pick slope from the contiguous (x, y) window with maximal |rho|.

    Used for the Lyapunov S(t) curve: the book defines lambda_max as the slope
    of the linear part of S(t) vs t. Instead of fixing t in [2, 10), we scan
    every contiguous window of at least `min_points` and keep the slope from
    the window with the highest absolute Pearson correlation.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    n = min(len(x), len(y))
    if n < min_points:
        return np.nan
    x = x[:n]
    y = y[:n]
    finite = np.isfinite(x) & np.isfinite(y)
    x = x[finite]
    y = y[finite]
    n = len(x)
    if n < min_points:
        return np.nan
    # Book connection:
    # Equation (8.94) states that nearby reconstructed states should separate
    # approximately exponentially under chaotic dynamics:
    #
    #   ||X_i(t+t0) - X_j(t+t0)|| ~= exp(lambda_max * t)
    #                                  ||X_i(t0) - X_j(t0)||
    #
    # Equation (8.95) then defines S(t) as an average log-distance growth over
    # reference states and their neighbourhoods. If an exponential-growth region
    # is present, S(t) is approximately linear in t, and the slope is lambda_max.
    #
    # The book examples show that the linear part can occupy different iteration
    # ranges for different systems and embedding dimensions. Therefore, scanning
    # every contiguous window is safer than hard-coding a fixed t interval.
    # We choose the window with the largest absolute Pearson correlation and use
    # its fitted slope as the LLE estimate.
    best_slope = np.nan
    best_rho = -np.inf
    best_width = 0
    for width in range(min_points, n + 1):
        for start in range(0, n - width + 1):
            stop = start + width
            xs = x[start:stop]
            ys = y[start:stop]
            rho = _pearson_abs(xs, ys)
            if not np.isfinite(rho):
                continue
            try:
                slope, _ = np.polyfit(xs, ys, 1)
            except Exception:
                continue
            if not np.isfinite(slope):
                continue
            if (rho, width) > (best_rho, best_width):
                best_rho = rho
                best_width = width
                best_slope = float(slope)
    return best_slope


def extract_lle_mean_std(lyap_file):
    """Largest Lyapunov estimate: slope of S(t) for the first m=3 epsilon block.

    lyap_k can output several epsilon blocks for the same embedding dimension.
    To keep LLE a single scalar, consistent with the thesis design, we take the
    first m=3 block and fit its best linear segment. There is no within-invariant
    vector here, so SD is reported as NaN and n as 1.
    """
    # The .lyap output contains blocks whose data rows are:
    #   column 1: iteration t,
    #   column 2: S(t), the averaged logarithmic stretching factor,
    #   column 3: number of contributing points.
    #
    # We use column 2 versus column 1 because equation (8.95) defines S(t), and
    # the paragraph after that equation states that the slope of the linear part
    # of S(t) is the largest Lyapunov exponent. This is why the code does not
    # average slopes over all epsilon blocks or all dimensions: the thesis uses
    # one scalar Kantz estimate for m=3.
    try:
        with open(lyap_file, "r", encoding="utf-8", errors="ignore") as handle:
            lines = handle.readlines()
        first_block = None
        current_block = []
        current_dim = None
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("#epsilon"):
                # A new lyap_k block starts. If the previous block was the first
                # m=3 block with data, stop immediately; later epsilon blocks
                # are deliberately ignored.
                if current_dim == M_LYAP and current_block:
                    first_block = np.array(current_block, dtype=float)
                    break
                current_dim = None
                current_block = []
                tokens = stripped.replace("=", " ").split()
                for idx, token in enumerate(tokens):
                    if token.lower() == "dim" and idx + 1 < len(tokens):
                        try:
                            current_dim = int(float(tokens[idx + 1]))
                        except ValueError:
                            current_dim = None
                        break
                continue
            if stripped.startswith("#") or stripped == "":
                continue
            if current_dim != M_LYAP:
                continue
            parts = stripped.split()
            if len(parts) >= 2:
                current_block.append([float(parts[0]), float(parts[1])])
        if first_block is None and current_dim == M_LYAP and current_block:
            first_block = np.array(current_block, dtype=float)
        if first_block is None or first_block.size == 0 or first_block.ndim < 2:
            return np.nan, np.nan, 0
        slope = _best_linear_slope(first_block[:, 0], first_block[:, 1])
        if not np.isfinite(slope):
            return np.nan, np.nan, 0
        return slope, np.nan, 1
    except Exception:
        return np.nan, np.nan, 0


def compute_percentile_radius(
    series,
    delay=1,
    m=RQA_EMBEDDING_DIM,
    percentile=RQA_RADIUS_PERCENTILE_DEFAULT,
    max_vectors=RQA_RADIUS_MAX_VECTORS,
    seed=RQA_RADIUS_SAMPLE_SEED,
):
    """Recurrence threshold as a percentile of pairwise Euclidean distances.

    Reconstructs the (m, delay) embedded state space and returns the requested
    percentile of pairwise Euclidean distances between embedded vectors. For
    long series the embedded matrix is randomly subsampled (without replacement,
    fixed RNG seed for reproducibility) down to `max_vectors` rows to keep pdist
    memory bounded. Returns NaN when the embedding cannot be built or when
    fewer than two embedded vectors are available.
    """
    delay = int(delay) if delay and int(delay) > 0 else 1
    m = int(m) if m and int(m) > 0 else 1
    embedded = embed_series(series, delay=delay, m=m)
    if max_vectors and embedded.shape[0] > max_vectors:
        # pdist is quadratic in the number of vectors. Subsampling keeps memory
        # and runtime predictable while preserving a stable radius estimate.
        rng = np.random.default_rng(seed)
        sample_idx = rng.choice(embedded.shape[0], size=max_vectors, replace=False)
        embedded = embedded[sample_idx]
    if embedded.shape[0] < 2:
        return float("nan")
    distances = pdist(embedded, metric="euclidean")
    if distances.size == 0:
        return float("nan")
    return float(np.percentile(distances, percentile))


def effective_rqa_theiler(theiler):
    """Use at least 1 so diagonal-line RQA metrics ignore the line of identity.

    PyRQA with theiler_corrector=0 includes the main diagonal. That makes
    MAXLINE equal to the full embedded series length, which is not meaningful
    for recurrence-line diagnostics. For metrics we force at least one excluded
    diagonal while still allowing the batch recurrence plot to use its own W.
    """
    try:
        return max(1, int(theiler))
    except Exception:
        return 1


def embed_series(series, delay=1, m=RQA_EMBEDDING_DIM):
    """Construct a standard delay-embedding matrix from a scalar series.

    Row i is (x_i, x_{i+delay}, ..., x_{i+(m-1)delay}). Non-finite input values
    are dropped before embedding so downstream distance calculations do not
    propagate NaNs.
    """
    data = np.asarray(series, dtype=float)
    finite_mask = np.isfinite(data)
    if not finite_mask.all():
        data = data[finite_mask]
    delay = int(delay) if delay and int(delay) > 0 else 1
    m = int(m) if m and int(m) > 0 else 1
    span = (m - 1) * delay
    if data.size <= span:
        return np.empty((0, m), dtype=float)
    n_vec = data.size - span
    offsets = np.arange(m, dtype=np.int64) * delay
    return data[np.arange(n_vec, dtype=np.int64)[:, None] + offsets[None, :]]


def rqa_recurrence_matrix(series, delay, radius, m=RQA_EMBEDDING_DIM):
    """Build a boolean recurrence matrix for diagnostics.

    This helper is intentionally simple and explicit. It is not used for the
    core PyRQA metrics, but it is useful for manual checks and for code that
    needs a concrete recurrence matrix rather than PyRQA's internal structures.
    """
    embedded = embed_series(series, delay=delay, m=m)
    if embedded.shape[0] < 2:
        return np.zeros((0, 0), dtype=bool)
    n = embedded.shape[0]
    recurrence = np.zeros((n, n), dtype=bool)
    radius = float(radius)
    # Row-wise computation avoids constructing an N x N x m temporary array.
    for i in range(n):
        diff = embedded - embedded[i]
        recurrence[i, :] = np.sqrt(np.sum(diff * diff, axis=1)) <= radius
    return recurrence


def compute_rqa_trend(series, delay, radius, theiler=1, m=RQA_EMBEDDING_DIM):
    """RQA TREND as linear slope of recurrence density along off-LOI diagonals.

    For each diagonal distance k from the line of identity, combine the +k and
    -k diagonals and compute their recurrence density. TREND is the ordinary
    least-squares slope of that density as a function of k. Diagonals inside
    the effective Theiler window are skipped.
    """
    embedded = embed_series(series, delay=delay, m=m)
    n = embedded.shape[0]
    if n < 3:
        return np.nan
    min_k = effective_rqa_theiler(theiler)
    xs = []
    ys = []
    radius = float(radius)
    for k in range(min_k, n):
        # The +k and -k diagonals contain the same distances for a symmetric
        # recurrence matrix, so computing embedded[:-k] vs embedded[k:] captures
        # the off-identity diagonal density without materializing the full matrix.
        diff = embedded[:-k] - embedded[k:]
        if diff.size == 0:
            continue
        recurrent = np.sqrt(np.sum(diff * diff, axis=1)) <= radius
        density = float(np.mean(recurrent))
        xs.append(float(k))
        ys.append(density)
    if len(xs) < 2:
        return np.nan
    try:
        slope, _ = np.polyfit(np.asarray(xs), np.asarray(ys), 1)
    except Exception:
        return np.nan
    return float(slope)


def format_rqa_radius(radius):
    """Stable string representation used in BAT run IDs and CLI arguments.

    A fixed precision prevents tiny floating-point formatting differences from
    creating different output-folder names for the same effective radius.
    """
    if radius is None or not np.isfinite(radius):
        return f"{DEFAULT_RQA_RADIUS:.10g}"
    return f"{float(radius):.10g}"


def compute_pyrqa_metrics(series, delay, theiler, radius=None):
    """Compute PyRQA scalar metrics for the full series.

    RQA is intentionally not segmented in this pipeline. Each metric is one
    scalar for the whole original series.
    TREND is added manually because the installed PyRQA API does not expose the
    exact off-identity diagonal-density slope needed here.
    """
    r_eff = float(DEFAULT_RQA_RADIUS if radius is None else radius)
    theiler_eff = effective_rqa_theiler(theiler)
    try:
        ts = TimeSeries(series, embedding_dimension=RQA_EMBEDDING_DIM, time_delay=delay)
        settings = Settings(ts, analysis_type=Classic,
                            neighbourhood=FixedRadius(r_eff),
                            similarity_measure=EuclideanMetric,
                            theiler_corrector=theiler_eff)
        computation = RQAComputation.create(settings, verbose=False)
        result = computation.run()
        result.min_diagonal_line_length = 2
        result.min_vertical_line_length = 2
        trend = compute_rqa_trend(series, delay=delay, radius=r_eff, theiler=theiler_eff)
        return {
            "RR": float(result.recurrence_rate),
            "DET": float(result.determinism),
            "LAM": float(result.laminarity),
            "MAXLINE": float(result.longest_diagonal_line),
            "ENTR": float(result.entropy_diagonal_lines),
            "TT": float(result.trapping_time),
            "TREND": float(trend),
        }
    except Exception:
        return {k: np.nan for k in RQA_KEYS}


def compute_invariants(series_array, output_dir, label, delay, theiler,
                       metric_names, rqa_radius=None, series_std_fallback=np.nan,
                       rqa_radius_mode="percentile",
                       rqa_percentile=RQA_RADIUS_PERCENTILE_DEFAULT,
                       rqa_radius_log=None):
    """Compute invariants for an in-memory series. Returns (mean_dict, sd_dict, n_dict).

    Value / SD / n sources:
      TAKENS — plateau mean of the c2t Takens-Theiler curve d_2^(T)(r') for
               embedding m=3. Its plateau end-points also define r_min/r_max.
      ELLNER — Ellner extension (eq. 8.78) evaluated on .c2 between the same
               r_min and r_max. The reported SD/n come from the Takens plateau
               dispersion and serve as an orientation for the interval quality.
      LLE   — slope of the linear part of S(t) for m=3
      RQA   — one metric value computed on the full time series

    `series_std_fallback` (the sample SD of the analysed series, sigma) is used
    to set the `d2.exe` evaluation range to [0.25*sigma, 0.5*sigma], matching
    the book's practical Takens scale recommendation.

    For RQA, the recurrence radius is selected dynamically when
    `rqa_radius_mode == 'percentile'` (default) as `rqa_percentile`-th percentile
    of pairwise Euclidean distances between embedded state vectors. If the
    percentile calculation cannot be performed, the function falls back to the
    explicit `rqa_radius` value (or `DEFAULT_RQA_RADIUS` if that is also missing).
    """
    metric_names = list(metric_names)

    # Work out which external tools are actually needed. This matters because
    # hypothesis.py is called many times during stationary bootstrap; skipping
    # unused executables saves a lot of runtime.
    need_takens = "TAKENS" in metric_names
    need_ellner = "ELLNER" in metric_names
    need_lle = "LLE" in metric_names
    need_rqa = any(k in metric_names for k in RQA_KEYS)

    # Every in-memory pseudo-series is written to a temporary .dat file because
    # TISEAN tools are command-line programs that operate on files, not arrays.
    prefix = os.path.join(output_dir, label)
    data_file = prefix + ".dat"
    np.savetxt(data_file, series_array)

    # The three output dictionaries share the same metric keys:
    #   out     -> point estimate used in comparisons,
    #   out_std -> within-curve/plateau SD where meaningful,
    #   out_n   -> number of values behind that SD.
    #
    # For bootstrap TS decisions, the important SD is later computed across the
    # B bootstrap point estimates, not from out_std.
    out = {k: np.nan for k in metric_names}
    out_std = {k: np.nan for k in metric_names}
    out_n = {k: 0 for k in metric_names}

    try:
        d2_file = h2_file = c2_file = None
        if need_takens or need_ellner:
            # Dimension metrics share one d2.exe call. The radius range is
            # tied to the original-series sigma passed by main(), so orig,
            # reshuffle, normal, t-reference, and bootstrap pseudo-series are
            # evaluated on a comparable scale grid.
            sigma = float(series_std_fallback) if np.isfinite(series_std_fallback) else np.nan
            if np.isfinite(sigma) and sigma > 0.0:
                eps_min = 0.25 * sigma
                eps_max = 0.5 * sigma
            else:
                eps_min = eps_max = None
            d2_file, h2_file, c2_file = run_d2(
                data_file, delay, theiler, prefix,
                eps_min=eps_min, eps_max=eps_max,
            )
        if (need_takens or need_ellner) and c2_file:
            # One c2t run supplies both TAKENS and ELLNER. TAKENS uses the
            # plateau mean directly. ELLNER reuses the plateau endpoints and
            # integrates the original .c2 correlation integral over that interval.
            #
            # Book mapping in this block:
            #   1. run_c2t() gives the Takens curve d_2^(T)(r') from (8.75)-(8.76).
            #   2. extract_takens_plateau() implements the recommended plateau
            #      search in d_2^(T)(r') vs ln(r') after (8.77).
            #   3. compute_ellner_from_c2() applies Ellner's finite-interval
            #      correction (8.78) on the same scaling region.
            takens_file = prefix + "_takens.dat"
            run_c2t(c2_file, takens_file)
            takens_mean, takens_sd, n_val, r_min, r_max = extract_takens_plateau(takens_file)
            if need_takens:
                out["TAKENS"] = takens_mean
                out_std["TAKENS"] = takens_sd
                out_n["TAKENS"] = int(n_val)
            if np.isfinite(r_min) and np.isfinite(r_max) and r_max > r_min:
                ellner = compute_ellner_from_c2(c2_file, r_min, r_max)
            else:
                ellner = np.nan
            if need_ellner:
                out["ELLNER"] = ellner
                out_std["ELLNER"] = takens_sd
                out_n["ELLNER"] = int(n_val) if np.isfinite(ellner) else 0
        if need_lle:
            # LLE is one scalar slope estimate. It is recomputed for
            # original/reference/bootstrap series when LLE is selected.
            #
            # Book mapping:
            #   run_lyap_k() estimates S(t), the averaged logarithmic divergence
            #   from (8.95), under the exponential-separation model (8.94).
            #   extract_lle_mean_std() then finds the linear part of S(t) and
            #   returns its slope as lambda_max.
            lyap_file = prefix + "_lyap.txt"
            run_lyap_k(data_file, delay, lyap_file)
            mu, sg, nn = extract_lle_mean_std(lyap_file)
            out["LLE"], out_std["LLE"] = mu, sg
            out_n["LLE"] = nn
        if need_rqa:
            # Radius selection is per analysed series by default. The same code
            # path is used by RQA.bat and direct hypothesis.py calls.
            r_eff = None
            source = "fixed"
            if str(rqa_radius_mode).lower() == "percentile":
                r_eff = compute_percentile_radius(
                    series_array,
                    delay=delay,
                    m=RQA_EMBEDDING_DIM,
                    percentile=rqa_percentile,
                )
                source = f"percentile({rqa_percentile:g}%)"
                if not (np.isfinite(r_eff) and r_eff > 0.0):
                    r_eff = None
                    source = "fixed (percentile failed)"
            if r_eff is None:
                # Fallback order: explicit --rqa_radius if valid, otherwise the
                # module default. This keeps RQA robust when the percentile
                # cannot be computed (for example very short series).
                r_eff = (
                    float(rqa_radius)
                    if rqa_radius is not None and np.isfinite(rqa_radius) and rqa_radius > 0.0
                    else float(DEFAULT_RQA_RADIUS)
                )
            print(
                f"     RQA radius for label={label}: r={r_eff:.6g}  "
                f"({source}, m={RQA_EMBEDDING_DIM}, tau={delay})"
            )
            if isinstance(rqa_radius_log, dict):
                rqa_radius_log[label] = {"radius": float(r_eff), "source": source}
            rqa_values = compute_pyrqa_metrics(series_array, delay, theiler, r_eff)
            for k in RQA_KEYS:
                if k in out:
                    value = float(rqa_values.get(k, np.nan))
                    out[k] = value
                    out_std[k] = np.nan
                    out_n[k] = 1 if np.isfinite(value) else 0
    except subprocess.CalledProcessError:
        logger.exception("TISEAN failed for label=%s", label)
    except Exception:
        logger.exception("Error computing invariants for label=%s", label)
    finally:
        # Each bootstrap iteration writes several temporary files. Remove every
        # file sharing the prefix so long runs do not fill the result directory.
        for tmp in glob.glob(prefix + "*"):
            try:
                os.remove(tmp)
            except OSError:
                pass

    return out, out_std, out_n


def parse_metrics_list(raw_metrics):
    """Normalize and validate a comma-separated CLI metric list."""
    tokens = [t.strip().upper() for t in str(raw_metrics).split(",") if t.strip()]
    if not tokens:
        raise ValueError("metrics list is empty")
    invalid = [t for t in tokens if t not in ALL_METRICS]
    if invalid:
        raise ValueError(f"unknown metric(s): {', '.join(invalid)}")
    return list(dict.fromkeys(tokens))


def metric_names_for_scope(_=None):
    # Direct dimension-hypothesis runs default to Ellner only. Batch scripts
    # that need LLE/RQA pass an explicit --metrics_list.
    return ["ELLNER"]


